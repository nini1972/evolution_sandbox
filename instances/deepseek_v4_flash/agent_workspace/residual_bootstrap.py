"""
HONEST AUDIT of the crossover claim. With only 6 N-points and 3 parameters,
a 2-term model can absorb curvature by construction. Two tests that can KILL it:

(A) RESIDUALS. A real law leaves structureless residuals. Compare observed
    ln(rate) vs each model's prediction; report standardized residuals and a
    runs/sign test. If crossover residuals show systematic sign runs, it is a
    smooth interpolant, not a law.

(B) DOUBLE BOOTSTRAP.
    - Nonparametric: resample the 6 (N, n_escaped, T) points with replacement,
      refit all 3 models, count how often each wins by AIC. If crossover "wins"
      only ~50% of resamples, the dAIC=92 is driven by 1-2 leverage points.
    - Parametric: simulate counts under the CROSSOVER model itself, refit all 3.
      If single-term models now win on data truly generated by crossover, the
      AIC penalty (k=3) is mis-calibrated -> crossover over-penalized, which
      would only STRENGTHEN it. If crossover still wins, its AIC edge is real.
"""
import json
import numpy as np
from scipy.optimize import minimize

D = json.load(open('km_barrier_corrected.json'))
rows = [r for r in D['rows'] if r['n_escaped'] > 0 and r['rate'] > 0]
Ns  = np.array([r['N'] for r in rows], float)
nev = np.array([r['n_escaped'] for r in rows], float)
tot = np.array([r['n_escaped'] / r['rate'] for r in rows], float)

def negll(params, form, N, n, T):
    c0, p1, p2 = params
    lnN = np.log(N)
    if form == 'kramers':
        lam = np.exp(c0 - p1 * N)
    elif form == 'power':
        lam = np.exp(c0 - p1 * lnN)
    else:
        lam = np.exp(c0 - p1 * N - p2 * lnN)
    lam = np.clip(lam, 1e-300, None)
    return -float(np.sum(n * np.log(lam) - lam * T))

STARTS = {'kramers': [[-3, 0.008, 0], [-2, 0.005, 0], [0, 0.002, 0]],
          'power': [[3, 1.55, 0], [2, 1.0, 0], [4, 2.0, 0]],
          'crossover': [[-1, 0.004, 0.8], [0, 0.002, 1.2], [1, 0.001, 2.0]]}

def fit(form, N, n, T):
    best = None
    for s0 in STARTS[form]:
        r = minimize(negll, s0, args=(form, N, n, T), method='Nelder-Mead',
                     options=dict(maxiter=60000, xatol=1e-9, fatol=1e-9))
        if best is None or r.fun < best.fun:
            best = r
    k = 2 if form != 'crossover' else 3
    return dict(ll=-best.fun, k=k, aic=2 * best.fun + 2 * k, params=best.x)

# ---- fit on real data
F = {f: fit(f, Ns, nev, tot) for f in STARTS}

print('=== (A) RESIDUALS: observed ln(rate) vs model prediction ===')
ln_obs = np.log(nev / tot)
lnN = np.log(Ns)
print('%6s %9s %9s %9s %9s' % ('N', 'ln_obs', 'kram_res', 'pow_res', 'cross_res'))
res = {'kramers': [], 'power': [], 'crossover': []}
for i in range(len(Ns)):
    N = Ns[i]
    rk = ln_obs[i] - (F['kramers']['params'][0] - F['kramers']['params'][1] * N)
    rp = ln_obs[i] - (F['power']['params'][0] - F['power']['params'][1] * lnN[i])
    rc = ln_obs[i] - (F['crossover']['params'][0] - F['crossover']['params'][1] * N
                      - F['crossover']['params'][2] * lnN[i])
    res['kramers'].append(rk); res['power'].append(rp); res['crossover'].append(rc)
    print('%6d %9.3f %9.3f %9.3f %9.3f' % (N, ln_obs[i], rk, rp, rc))

def sign_runs(r):
    s = np.sign(r); runs = 1 + np.sum(s[1:] != s[:-1])
    return int(runs), int(np.sum(s > 0))

print('\nresidual RMS and sign-run structure (6 pts; runs ~1 = systematic bias):')
for f in ['kramers', 'power', 'crossover']:
    r = np.array(res[f]); runs, npos = sign_runs(r)
    print('%-10s RMS=%.4f  mean=%.4f  sign-runs=%d  n(+)=%d/6'
          % (f, np.sqrt(np.mean(r**2)), r.mean(), runs, npos))

# ---- (B) nonparametric bootstrap: resample 6 points WITH replacement
rng = np.random.default_rng(20240517)
NB = 2000
wins = {'kramers': 0, 'power': 0, 'crossover': 0}
boot_params = {'kramers': [], 'power': [], 'crossover': []}
for b in range(NB):
    idx = rng.integers(0, len(Ns), len(Ns))
    N, n, T = Ns[idx], nev[idx], tot[idx]
    aics = {}
    for f in STARTS:
        try:
            ff = fit(f, N, n, T)
            aics[f] = ff['aic']
            boot_params[f].append(ff['params'])
        except Exception:
            aics[f] = np.inf
    wins[min(aics, key=aics.get)] += 1

print('\n=== (B1) NONPARAMETRIC bootstrap (resample 6 pts, %d reps) ===' % NB)
for f in ['kramers', 'power', 'crossover']:
    print('  %-10s wins %4d / %d  (%5.1f%%)'
          % (f, wins[f], NB, 100 * wins[f] / NB))
    P = np.array(boot_params[f])
    if len(P):
        ci = np.percentile(P, [2.5, 97.5], axis=0)
        print('     param 95%% CI: %s' % np.round(ci, 4).tolist())

# ---- (B2) parametric bootstrap under crossover-truth
c0t, c1t, bt = F['crossover']['params']
lam_true = np.exp(c0t - c1t * Ns - bt * lnN)
win2 = {'kramers': 0, 'power': 0, 'crossover': 0}
for b in range(NB):
    # T fixed, events ~ Poisson(lam*T) capped at total; use binomial for count
    p = np.clip(lam_true * tot / np.maximum(tot, 1e-9), 0, 1)
    n_sim = rng.binomial(tot.astype(int), np.clip(lam_true, 0, 1) * np.ones_like(tot)
                         * 0 + np.clip(lam_true, 0, 1))
    # simpler & correct: expected events = lam_true*tot ; Poisson draw
    n_sim = rng.poisson(lam_true * tot).astype(float)
    n_sim = np.minimum(n_sim, tot)
    aics = {}
    for f in STARTS:
        try:
            aics[f] = fit(f, Ns, n_sim, tot)['aic']
        except Exception:
            aics[f] = np.inf
    win2[min(aics, key=aics.get)] += 1

print('\n=== (B2) PARAMETRIC bootstrap under CROSSOVER truth (%d reps) ===' % NB)
for f in ['kramers', 'power', 'crossover']:
    print('  %-10s wins %4d / %d  (%5.1f%%)'
          % (f, win2[f], NB, 100 * win2[f] / NB))

out = dict(
    residuals={f: [float(x) for x in res[f]] for f in res},
    fit_aic={f: float(F[f]['aic']) for f in F},
    fit_params={f: [float(x) for x in F[f]['params']] for f in F},
    nonparam_wins={f: wins[f] for f in wins},
    param_wins={f: win2[f] for f in win2},
    NB=NB,
)
json.dump(out, open('residual_bootstrap.json', 'w'), indent=1)
print('\nsaved residual_bootstrap.json')
